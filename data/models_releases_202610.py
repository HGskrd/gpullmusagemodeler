RELEASE_CAPTURED_AT = "2026-10-27"
RELEASE_MODELS: dict[str, Model] = {}
RELEASE_EVIDENCE: dict[str, dict] = {}


def _register(
    model: Model,
    repository: str,
    revision: str,
    license_name: str,
    artifact_bytes: int,
    *,
    dtype_counts: dict | None = None,
    storage_evidence: str = "pinned tensor payload bytes",
    compute_shares: dict | None = None,
    active_bpp: float | None = None,
    artifact_exact: bool = True,
    container: str = "safetensors",
    source_note: str = "",
) -> None:
    note = (
        f"License: {license_name}. Captured {RELEASE_CAPTURED_AT}. "
        "Closed-form capacity estimate; throughput and quality are uncalibrated. "
        + model.architecture_note
    )
    label = model.native_precision_label
    if model.key == "minimax-m3.1-flash":
        label = "Mixed NVFP4 / MXFP8"
    elif model.key == "dory1-4b-2loop":
        label = "MXFP8 W8A16"
    elif model.key.startswith("apertus15"):
        label = "BF16 + FP32 tokenizers"
    model = replace(
        model,
        architecture_note=note,
        quality_confidence=0.0,
        native_precision_label=label,
        native_precision_note=(model.native_precision_note or note)
        + " Cache precision is independent of checkpoint precision; default cache is BF16.",
    )
    RELEASE_MODELS[model.key] = model
    reference = (
        f"https://github.com/{repository}"
        if repository == "facebookresearch/omnilingual-asr"
        else f"https://huggingface.co/{repository}"
    )
    config_path = (
        "src/omnilingual_asr/cards/models/rc_models_v2.yaml"
        if repository == "facebookresearch/omnilingual-asr"
        else "config.json"
    )
    OPEN_MODEL_ARCHITECTURE_SOURCES[model.key] = ModelArchitectureSource(
        reference,
        revision,
        note + " " + source_note,
        config_path,
    )
    RELEASE_EVIDENCE[model.key] = {
        "repository": repository,
        "revision": revision,
        "license": license_name,
        "captured_at": RELEASE_CAPTURED_AT,
        "checkpoint_bytes": artifact_bytes,
        "storage_evidence": storage_evidence,
        "notes": note + " " + source_note,
    }
    precision = model.native_precision_key
    scheme = None
    if dtype_counts and set(dtype_counts) == {"F32"}:
        scheme = QuantizationScheme("FP32 storage", (), "none")
    elif dtype_counts and "F16" in dtype_counts:
        scheme = QuantizationScheme("FP16 storage + FP32 auxiliary tensors", (), "none")
    if model.key == "granite-speech-5.0-2b":
        dtype_counts = {**(dtype_counts or {}), "I64": 16}
    pair = _artifact_profile(
        model_key=model.key,
        precision_key=precision,
        label=model.native_precision_display,
        source_repo=repository,
        source_revision=revision,
        total_weight_bytes=artifact_bytes,
        storage_format_counts=dtype_counts or {},
        compute_precision_shares=compute_shares or {"bf16": 1.0},
        quantized=() if precision == "bf16" else (model.attention_label,),
        retained=("Full selected serving checkpoint and resident auxiliary components.",),
        notes=note + " " + source_note,
        quant_algo="Unquantized" if precision == "bf16" else model.native_precision_display,
        kv_cache_format="BF16",
        captured_at=RELEASE_CAPTURED_AT,
        storage_evidence=storage_evidence,
        container=container,
        scheme=scheme,
    )
    MODEL_QUANTIZATION_PROFILES[pair[0]] = replace(
        pair[1],
        source_kind="exact" if artifact_exact else "estimate",
        active_weight_bytes_per_param_override=active_bpp,
        source_url=(f"{reference}/tree/{revision}" if container == "pytorch" else ""),
    )


